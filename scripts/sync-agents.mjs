import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  process.stderr.write('Usage: node scripts/sync-agents.mjs [--check]\n');
  process.exit(1);
}

try {
  const source = await readFile(join(root, 'SKILL.md'), 'utf8');
  // This repository uses two single-line frontmatter fields, not general YAML.
  const policy = /^---\nname: (phlegon)\ndescription: ([^\n]+)\n---\n+([\s\S]+)$/.exec(source);
  if (!policy || !policy[2].trim() || !policy[3].trim() ||
      !source.isWellFormed() || /[\u0000-\u0008\u000b-\u001f\u007f]/.test(source)) {
    process.stderr.write('SKILL.md must have name: phlegon, a single-line description and a nonempty policy body using LF newlines.\n');
    process.exit(1);
  }
  const [, name, description, body] = policy;
  const generated = '# Generated by scripts/sync-agents.mjs from SKILL.md.\n';
  const artifacts = new Map([
    ['.plugins/claude/.claude-plugin/plugin.json', JSON.stringify({
      name,
      version: '0.1.0',
      description,
    }, null, 2) + '\n'],
    ['.plugins/claude/agents/phlegon.md', `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\nmodel: inherit\n---\n\n${body}`],
    ['.plugins/claude/skills/phlegon/SKILL.md', source],
    ['.codex/agents/phlegon.toml', generated +
      `name = ${JSON.stringify(name)}\n` +
      `description = ${JSON.stringify(description)}\n` +
      `developer_instructions = ${JSON.stringify(body)}\n`],
  ]);

  for (const [relative, content] of artifacts) {
    const target = join(root, relative);
    if (args[0] === '--check') {
      let current;
      try {
        current = await readFile(target, 'utf8');
      } catch (error) {
        if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT') throw error;
        process.stderr.write(`Missing generated artifact: ${relative}\n`);
        process.exitCode = 1;
        continue;
      }
      if (current !== content) {
        process.stderr.write(`Stale generated artifact: ${relative}\n`);
        process.exitCode = 1;
      }
    } else {
      await mkdir(dirname(target), { recursive: true });
      await writeFile(target, content);
    }
  }
  if (!process.exitCode) process.stdout.write(args[0] === '--check'
    ? 'Generated artifacts are current.\n'
    : 'Generated 4 artifacts from SKILL.md.\n');
} catch (error) {
  if (!(error instanceof Error)) throw error;
  process.stderr.write('Unable to synchronize generated artifacts; check source and output file permissions.\n');
  process.exitCode = 1;
}
